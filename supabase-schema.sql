-- Служебные RBAC-функции не должны быть доступны через публичный RPC.
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated, service_role;

create or replace function private.is_superteacher()
returns boolean language sql stable security definer set search_path=''
as $$
  select exists(
    select 1 from public.profiles
    where id=(select auth.uid()) and role='superteacher' and is_active=true and archived=false
  );
$$;

create or replace function private.is_teacher()
returns boolean language sql stable security definer set search_path=''
as $$
  select exists(
    select 1 from public.profiles
    where id=(select auth.uid()) and role='teacher' and is_active=true and archived=false
  );
$$;

create or replace function private.teacher_has_student(p_student uuid)
returns boolean language sql stable security definer set search_path=''
as $$
  select private.is_superteacher() or (
    private.is_teacher() and exists(
      select 1 from public.teacher_student_assignments
      where teacher_id=(select auth.uid()) and student_id=p_student
    )
  );
$$;

create or replace function private.teacher_has_course(p_level integer)
returns boolean language sql stable security definer set search_path=''
as $$
  select private.is_superteacher() or (
    private.is_teacher() and exists(
      select 1 from public.teacher_course_assignments
      where teacher_id=(select auth.uid()) and course_level=p_level
    )
  );
$$;

create or replace function private.teacher_can_manage_student_course(p_student uuid,p_level integer)
returns boolean language sql stable security definer set search_path=''
as $$
  select private.is_superteacher() or (
    private.is_teacher()
    and exists(select 1 from public.teacher_student_assignments where teacher_id=(select auth.uid()) and student_id=p_student)
    and exists(select 1 from public.teacher_course_assignments where teacher_id=(select auth.uid()) and course_level=p_level)
    and exists(select 1 from public.course_access where student_id=p_student and course_level=p_level and access_granted=true)
    and exists(select 1 from public.profiles where id=p_student and role='student' and is_active=true and archived=false)
  );
$$;

revoke all on function private.is_superteacher() from public, anon;
revoke all on function private.is_teacher() from public, anon;
revoke all on function private.teacher_has_student(uuid) from public, anon;
revoke all on function private.teacher_has_course(integer) from public, anon;
revoke all on function private.teacher_can_manage_student_course(uuid,integer) from public, anon;
grant execute on function private.is_superteacher() to authenticated, service_role;
grant execute on function private.is_teacher() to authenticated, service_role;
grant execute on function private.teacher_has_student(uuid) to authenticated, service_role;
grant execute on function private.teacher_has_course(integer) to authenticated, service_role;
grant execute on function private.teacher_can_manage_student_course(uuid,integer) to authenticated, service_role;

