create policy "course access select" on public.course_access for select to authenticated
using(
  private.is_superteacher()
  or private.teacher_can_manage_student_course(student_id,course_level)
  or (
    student_id=(select auth.uid())
    and exists(
      select 1 from public.profiles p
      where p.id=(select auth.uid()) and p.role='student' and p.is_active=true and p.archived=false
    )
  )
);
create policy "course access insert" on public.course_access for insert to authenticated
with check(private.is_superteacher());
create policy "course access update" on public.course_access for update to authenticated
using(private.is_superteacher()) with check(private.is_superteacher());
create policy "course access delete" on public.course_access for delete to authenticated
using(private.is_superteacher());

create policy "materials select" on public.course_materials for select to authenticated
using(
  private.is_superteacher()
  or (private.is_teacher() and private.teacher_has_course(course_level))
  or (
    published=true
    and exists(
      select 1 from public.course_access ca
      join public.profiles p on p.id=ca.student_id
      where ca.student_id=(select auth.uid())
        and ca.course_level=course_materials.course_level
        and ca.access_granted=true
        and p.role='student' and p.is_active=true and p.archived=false
    )
    and (
      course_materials.module_no=1
      or (
        select count(*) from public.student_progress sp
        where sp.student_id=(select auth.uid())
          and sp.course_level=course_materials.course_level
          and sp.completed=true
          and sp.module_no<course_materials.module_no
      )=course_materials.module_no-1
    )
  )
);
create policy "materials insert" on public.course_materials for insert to authenticated
with check(private.is_superteacher());
create policy "materials update" on public.course_materials for update to authenticated
using(private.is_superteacher()) with check(private.is_superteacher());
create policy "materials delete" on public.course_materials for delete to authenticated
using(private.is_superteacher());

