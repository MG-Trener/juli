-- Регистрация: профиль создаётся серверным триггером, роль из user_metadata не используется.
create or replace function private.handle_new_user()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  insert into public.profiles(id,email,full_name,role,is_active,archived)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name',''),'candidate',true,false)
  on conflict(id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure private.handle_new_user();
drop function if exists public.handle_new_user();
revoke all on function private.handle_new_user() from public, anon, authenticated;

